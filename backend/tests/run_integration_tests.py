# ---------- Tests ----------

def test_health_still_works():
    r = urllib.request.urlopen(f"{BASE}/api/health")
    data = json.loads(r.read())
    assert data["status"] == "ok"
    print("PASS  /api/health still works")


def test_real_pdf_with_skill_matching():
    """Sample resume contains Python, FastAPI, SQL, Docker, PostgreSQL, Git."""
    pdf_path = os.path.join(FIXTURES_DIR, "sample_resume.pdf")
    job = (
        "We are looking for a Python backend developer "
        "with FastAPI, SQL, Docker, and AWS experience."
    )
    status, data = _multipart_post(pdf_path, job)
    assert status == 200, f"Expected 200, got {status}: {data}"

    matched_names = [s["skill"] for s in data["matched_skills"]]
    missing_names = [s["skill"] for s in data["missing_skills"]]

    # Python, FastAPI, Docker should be matched
    for skill in ["Python", "FastAPI", "Docker"]:
        assert skill in matched_names, f"Expected '{skill}' in matched: {matched_names}"

    # AWS is in the job but not in the sample resume
    assert "AWS" in missing_names, f"Expected 'AWS' in missing: {missing_names}"

    assert isinstance(data["match_score"], int)
    assert 0 <= data["match_score"] <= 100
    assert "estimated score" in data["summary"]
    assert "temporary" not in data["summary"].lower()
    assert data["top_resume_matches"], "Expected vector search matches"
    top_match = data["top_resume_matches"][0]
    assert "job_requirement" in top_match
    assert "resume_chunk" in top_match
    assert "similarity_score" in top_match
    assert top_match["similarity_score"] >= 0.35
    assert "embeddings" not in data
    print(f"PASS  real PDF skill matching (matched={matched_names}, missing={missing_names})")


