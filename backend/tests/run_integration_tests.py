def test_bad_extension_rejected():
    status, data = _fake_multipart_post(
        "resume.txt",
        "Python developer with FastAPI, SQL, Docker, and AWS experience required.",
    )
    assert status == 400
    assert "Unsupported file type" in data["detail"]
    print("PASS  bad extension rejected")


