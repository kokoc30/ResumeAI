"""Integration tests for POST /api/analyze with real resume files.

Requires the server running on http://127.0.0.1:8000
and test fixtures generated by create_test_files.py.
"""

import json
import os
import urllib.request
import urllib.error

BASE = "http://127.0.0.1:8000"
FIXTURES_DIR = os.path.join(os.path.dirname(__file__), "fixtures")


def _multipart_post(filepath: str, job_desc: str) -> tuple[int, dict]:
    """Send a real file via multipart/form-data POST."""
    boundary = "----IntegTestBoundary7777"
    filename = os.path.basename(filepath)

    with open(filepath, "rb") as f:
        file_data = f.read()

    # Build multipart body manually
    body = bytearray()

    # File part
    body.extend(f"--{boundary}\r\n".encode())
    body.extend(
        f'Content-Disposition: form-data; name="resume_file"; '
        f'filename="{filename}"\r\n'.encode()
    )
    body.extend(b"Content-Type: application/octet-stream\r\n\r\n")
    body.extend(file_data)
    body.extend(b"\r\n")

    # job_description part
    body.extend(f"--{boundary}\r\n".encode())
    body.extend(
        b'Content-Disposition: form-data; name="job_description"\r\n\r\n'
    )
    body.extend(job_desc.encode())
    body.extend(b"\r\n")

    body.extend(f"--{boundary}--\r\n".encode())

    req = urllib.request.Request(
        f"{BASE}/api/analyze",
        data=bytes(body),
        headers={"Content-Type": f"multipart/form-data; boundary={boundary}"},
        method="POST",
    )

    try:
        resp = urllib.request.urlopen(req)
        return resp.status, json.loads(resp.read())
    except urllib.error.HTTPError as e:
        return e.code, json.loads(e.read())


